using System;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace LumenWave
{
    /// <summary>
    /// Persistent root object (DontDestroyOnLoad) holding global services: BeatClock, audio, MALink...
    /// Subsystems add themselves via <see cref="Register"/> from their own RuntimeInitializeOnLoadMethod.
    /// </summary>
    public static class GameSystems
    {
        static GameObject _root;
        static readonly List<Action<GameObject>> _installers = new List<Action<GameObject>>();

        public static GameObject Root
        {
            get
            {
                if (_root == null)
                {
                    _root = new GameObject("LumenWaveSystems");
                    if (Application.isPlaying) UnityEngine.Object.DontDestroyOnLoad(_root);
                    foreach (var i in _installers) i(_root);
                }
                return _root;
            }
        }

        /// <summary>Installs a global component once (now if the root exists, otherwise when it is created).</summary>
        public static void Register(Action<GameObject> installer)
        {
            _installers.Add(installer);
            if (_root != null) installer(_root);
        }

        public static T Get<T>() where T : Component
        {
            var c = Root.GetComponent<T>();
            return c != null ? c : Root.AddComponent<T>();
        }

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        static void ResetStatics()
        {
            _root = null;
            _installers.Clear();
            GameEvents.ResetAll();
        }

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
        static void Boot()
        {
            Application.targetFrameRate = 120;
            LumenInput.Ensure();
            Settings.Apply();
            var _ = Root;
            Get<BeatClock>();
        }
    }

    /// <summary>Run state: current level, timer, deaths. Survives scene loads.</summary>
    public static class GameSession
    {
        public static int CurrentLevel = 1;
        public static float LevelTime;
        public static float TotalTime;
        public static int Deaths;
        public static bool Paused;
        /// <summary>When true the run is driven by a bot (tests / attract mode).</summary>
        public static bool BotMode;

        public static void NewRun()
        {
            CurrentLevel = 1; LevelTime = 0; TotalTime = 0; Deaths = 0; Paused = false;
        }
    }

    /// <summary>Scene naming + transitions. Scenes are generated by LumenWave/Build All Levels.</summary>
    public static class SceneFlow
    {
        public const string TitleScene = "Title";
        public const string EndScene = "End";
        public static string LevelScene(int n) => "Level" + n.ToString("00");

        public static int LevelCount => LevelDatabase.Count;

        public static void LoadTitle() { GameSession.Paused = false; Time.timeScale = 1f; SceneManager.LoadScene(TitleScene); }
        public static void LoadEnd() { GameSession.Paused = false; Time.timeScale = 1f; SceneManager.LoadScene(EndScene); }

        public static void LoadLevel(int n)
        {
            GameSession.Paused = false;
            Time.timeScale = 1f;
            GameSession.CurrentLevel = n;
            GameSession.LevelTime = 0f;
            var scene = LevelScene(n);
            if (Application.CanStreamedLevelBeLoaded(scene)) SceneManager.LoadScene(scene);
            else
            {
                // Fallback: generic scene + loader picks level from GameSession.
                Debug.LogWarning("[LumenWave] Scene " + scene + " not in build, loading level " + n + " into the Level01 shell");
                SceneBootstrap.PendingLevelOverride = n;
                SceneManager.LoadScene(LevelScene(1));
            }
        }

        public static void NextLevel()
        {
            if (GameSession.CurrentLevel >= LevelCount) { GameEvents.RaiseGameWon(); LoadEnd(); }
            else LoadLevel(GameSession.CurrentLevel + 1);
        }
    }

    /// <summary>Player settings persisted in PlayerPrefs.</summary>
    public static class Settings
    {
        public static float MasterVolume { get => PlayerPrefs.GetFloat("lw.vol.master", 0.8f); set { PlayerPrefs.SetFloat("lw.vol.master", value); Apply(); } }
        public static float MusicVolume { get => PlayerPrefs.GetFloat("lw.vol.music", 0.7f); set => PlayerPrefs.SetFloat("lw.vol.music", value); }
        public static float SfxVolume { get => PlayerPrefs.GetFloat("lw.vol.sfx", 0.8f); set => PlayerPrefs.SetFloat("lw.vol.sfx", value); }
        public static bool ScreenShake { get => PlayerPrefs.GetInt("lw.shake", 1) == 1; set => PlayerPrefs.SetInt("lw.shake", value ? 1 : 0); }
        public static bool Fullscreen { get => PlayerPrefs.GetInt("lw.fullscreen", 1) == 1; set { PlayerPrefs.SetInt("lw.fullscreen", value ? 1 : 0); Screen.fullScreen = value; } }

        public static void Apply()
        {
            AudioListener.volume = MasterVolume;
        }
    }
}
